// ============ UTILITY FUNCTIONS ============

const downloadFile = (content: string, filename: string, mimeType: string) => {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

const copyToClipboard = async (text: string): Promise<boolean> => {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
};

// ============ MAIN COMPONENT ============

interface ReportGeneratorProps {
  trigger?: React.ReactNode;
  onDataRequest?: () => Promise<DebateData | SearchSessionData | Array<{role: string; content: string; model?: string}> | null>;
  defaultType?: ReportType;
}

export function ReportGenerator({ trigger, onDataRequest, defaultType = 'custom' }: ReportGeneratorProps) {
  const [open, setOpen] = useState(false);
  const [format, setFormat] = useState<ReportFormat>('markdown');
  const [reportType, setReportType] = useState<ReportType>(defaultType);
  const [reportContent, setReportContent] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  const [copied, setCopied] = useState(false);
  const [downloaded, setDownloaded] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const generateReport = useCallback(async () => {
    setIsGenerating(true);
    setError(null);

    try {
      let data;

      if (onDataRequest) {
        data = await onDataRequest();
      } else {
        // Generate sample data if no callback provided
        data = getSampleData(reportType);
      }

      if (!data) {
        throw new Error('No data available for report generation');
      }

      let content = '';

      if (Array.isArray(data)) {
        // AI Chat format
        content = generateAIChatReport(data, format);
      } else if ('rounds' in data) {
        // Debate format
        content = generateDebateReport(data, format);
      } else if ('papers' in data) {
        // Search format
        content = generateSearchReport(data, format);
      } else {
        throw new Error('Unknown data format');
      }

      setReportContent(content);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to generate report');
    } finally {
      setIsGenerating(false);
    }
  }, [format, reportType, onDataRequest]);

  const handleCopy = async () => {
    if (!reportContent) return;
    const success = await copyToClipboard(reportContent);
    if (success) {
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleDownload = () => {
    if (!reportContent) return;

    const extensions: Record<ReportFormat, string> = {
      text: 'txt',
      markdown: 'md',
      json: 'json',
      bibtex: 'bib',
    };

    const mimeTypes: Record<ReportFormat, string> = {
      text: 'text/plain',
      markdown: 'text/markdown',
      json: 'application/json',
      bibtex: 'text/plain',
    };

    const filename = `scihub-report-${new Date().toISOString().split('T')[0]}.${extensions[format]}`;
    downloadFile(reportContent, filename, mimeTypes[format]);
    
    setDownloaded(true);
    setTimeout(() => setDownloaded(false), 2000);
  };

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogTrigger asChild>
        {trigger || (
          <Button variant="outline" className="gap-2">
            📄 Generate Report
          </Button>
        )}
      </DialogTrigger>

      <DialogContent className="max-w-4xl max-h-[85vh] overflow-hidden flex flex-col">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            📊 Report Generator
          </DialogTitle>
          <DialogDescription>
            Generate formatted reports from your research activities
          </DialogDescription>
        </DialogHeader>

        <div className="flex-1 overflow-y-auto space-y-6 mt-4">
          {/* Options */}
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="text-sm font-medium mb-2 block">Report Type</label>
              <Select value={reportType} onValueChange={(v) => setReportType(v as ReportType)}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="debate">🎯 Debate Summary</SelectItem>
                  <SelectItem value="search">🔍 Literature Search</SelectItem>
                  <SelectItem value="ai_chat">🤖 AI Conversation</SelectItem>
                  <SelectItem value="custom">📝 Custom/Blank</SelectItem>
                </SelectContent>
              </Select>
            </div>

            <div>
              <label className="text-sm font-medium mb-2 block">Output Format</label>
              <Select value={format} onValueChange={(v) => setFormat(v as ReportFormat)}>
                <SelectTrigger><SelectValue /></SelectTrigger>
                <SelectContent>
                  <SelectItem value="markdown">📝 Markdown (.md)</SelectItem>
                  <SelectItem value="text">📄 Plain Text (.txt)</SelectItem>
                  <SelectItem value="json">📋 JSON (.json)</SelectItem>
                  <SelectItem value="bibtex">📚 BibTeX (.bib)</SelectItem>
                </SelectContent>
              </Select>
            </div>
          </div>

          {/* Generate Button */}
          {!reportContent && (
            <Card className="border-dashed">
              <CardContent className="p-8 text-center">
                <span className="text-4xl block mb-4">📊</span>
                <h3 className="font-semibold mb-2">Generate Your Report</h3>
                <p className="text-sm text-muted-foreground mb-4">
                  Click the button below to generate a {format.toUpperCase()} report
                </p>
                <Button onClick={generateReport} disabled={isGenerating}>
                  {isGenerating ? '⏳ Generating...' : '✨ Generate Report'}
                </Button>
              </CardContent>
            </Card>
          )}

          {/* Error */}
          {error && (
            <Card className="border-red-200 dark:border-red-800 bg-red-50 dark:bg-red-950">
              <CardContent className="p-4 flex items-center justify-between">
                <span className="text-sm text-red-700 dark:text-red-300">❌ {error}</span>
                <Button variant="ghost" size="sm" onClick={() => setError(null)}>Dismiss</Button>
              </CardContent>
            </Card>
          )}

          {/* Report Preview */}
          {reportContent && (
            <>
              <div className="flex items-center justify-between">
                <h4 className="font-medium">Report Preview ({format.toUpperCase()})</h4>
                <div className="flex gap-2">
                  <Button size="sm" variant="outline" onClick={handleCopy}>
                    {copied ? '✅ Copied!' : '📋 Copy'}
                  </Button>
                  <Button size="sm" onClick={handleDownload}>
                    {downloaded ? '✅ Downloaded!' : '💾 Download'}
                  </Button>
                  <Button size="sm" variant="ghost" onClick={() => setReportContent('')}>
                    🔄 Regenerate
                  </Button>
                </div>
              </div>

              <Card>
                <CardContent className="p-0">
                  <pre className="p-4 text-xs overflow-auto max-h-[400px] whitespace-pre-wrap bg-muted/50 rounded-lg">
                    {reportContent}
                  </pre>
                </CardContent>
              </Card>

              {/* Quick Stats */}
              <div className="grid grid-cols-3 gap-4 text-center text-sm">
                <div className="p-3 bg-muted/50 rounded-lg">
                  <div className="font-bold">{reportContent.split('\n').length}</div>
                  <div className="text-xs text-muted-foreground">Lines</div>
                </div>
                <div className="p-3 bg-muted/50 rounded-lg">
                  <div className="font-bold">{reportContent.length}</div>
                  <div className="text-xs text-muted-foreground">Characters</div>
                </div>
                <div className="p-3 bg-muted/50 rounded-lg">
                  <div className="font-bold">{Math.ceil(reportContent.length / 1024)}KB</div>
                  <div className="text-xs text-muted-foreground">Size</div>
                </div>
              </div>
            </>
          )}
        </div>
      </DialogContent>
    </Dialog>
  );
}

