// ============ TYPES ============

type ReportFormat = 'text' | 'markdown' | 'json' | 'bibtex';
type ReportType = 'debate' | 'search' | 'ai_chat' | 'custom';

interface ReportData {
  title: string;
  type: ReportType;
  date: Date;
  author?: string;
  sections: ReportSection[];
  metadata?: Record<string, any>;
}

interface ReportSection {
  heading: string;
  content: string;
  type?: 'text' | 'list' | 'table' | 'code';
}

interface DebateData {
  topic: string;
  participants: string[];
  rounds: Array<{
    speaker: string;
    argument: string;
    timestamp: Date;
  }>;
  conclusion?: string;
  winner?: string;
}

interface SearchSessionData {
  query: string;
  resultsCount: number;
  papers: Array<{
    title: string;
    authors: string[];
    year: number;
    source: string;
    citations: number;
  }>;
  filters?: Record<string, any>;
}

// ============ REPORT TEMPLATES ============

const generateDebateReport = (data: DebateData, format: ReportFormat): string => {
  const date = new Date().toLocaleDateString('en-US', { 
    year: 'numeric', month: 'long', day: 'numeric',
    hour: '2-digit', minute: '2-digit'
  });

  switch (format) {
    case 'markdown':
      return `# Debate Report: ${data.topic}

**Generated:** ${date}  
**Participants:** ${data.participants.join(', ')}

---

## Summary

This report documents a debate on "${data.topic}" featuring ${data.participants.length} participants.

## Debate Rounds

${data.rounds.map((round, i) => `
### Round ${i + 1}: ${round.speaker}

${round.argument}

*Timestamp: ${round.timestamp.toLocaleTimeString()}*
`).join('\n---\n')}

${data.conclusion ? `## Conclusion\n\n${data.conclusion}` : ''}

${data.winner ? `## Winner\n\n**${data.winner}**` : ''}

---
*Generated by SciHub Pro - Scientific Research Platform*
`;

    case 'json':
      return JSON.stringify({
        type: 'debate_report',
        generated_at: new Date().toISOString(),
        ...data
      }, null, 2);

    case 'text':
    default:
      return `DEBATE REPORT: ${data.topic}
${'='.repeat(50)}

Generated: ${date}
Participants: ${data.participants.join(', ')}

${'='.repeat(50)}

DEBATE ROUNDS
${'-'.repeat(40)}

${data.rounds.map((round, i) => 
`ROUND ${i + 1}: ${round.speaker}
${'-'.repeat(30)}
${round.argument}

[${round.timestamp.toLocaleTimeString()}]`
).join('\n\n')}

${data.conclusion ? `\n${'='.repeat(50)}\nCONCLUSION\n${'='.join(50)}\n\n${data.conclusion}` : ''}

${data.winner ? `\nWINNER: ${data.winner}` : ''}

${'='.repeat(50)}
Generated by SciHub Pro - Scientific Research Platform`;
  }
};

