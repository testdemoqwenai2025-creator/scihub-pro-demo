// ============ EXPORT HOOK ============

export function useReportGenerator() {
  const generateAndDownload = useCallback((
    data: DebateData | SearchSessionData | Array<{role: string; content: string; model?: string}>,
    format: ReportFormat = 'markdown',
    filename?: string
  ) => {
    let content = '';

    if (Array.isArray(data)) {
      content = generateAIChatReport(data, format);
    } else if ('rounds' in data) {
      content = generateDebateReport(data, format);
    } else if ('papers' in data) {
      content = generateSearchReport(data, format);
    }

    if (content) {
      const extensions: Record<ReportFormat, string> = {
        text: 'txt', markdown: 'md', json: 'json', bibtex: 'bib',
      };
      const finalFilename = filename || `scihub-report-${new Date().toISOString().split('T')[0]}.${extensions[format]}`;
      downloadFile(content, finalFilename, 'text/plain');
      return true;
    }
    return false;
  }, []);

  return { generateAndDownload };
}

